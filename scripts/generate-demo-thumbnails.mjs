import {readFile,writeFile} from 'node:fs/promises';
import {resolve,join} from 'node:path';
import {pathToFileURL} from 'node:url';

/** Bundle two small official previews so reconnecting pages need no late image fetch.
 * @param {string} source Browser source directory.
 * @returns {Promise<void>} Writes the browser module from the original JPEG files.
 */
export async function generateDemoThumbnails(source=resolve('dist')) {
  const thumbnails={};
  for(const name of ['coffee-demo','ai-demo']){
    const bytes=await readFile(join(source,'assets',name+'.jpg'));
    if(bytes[0]!==0xff||bytes[1]!==0xd8||bytes.length>32768)throw new Error('Invalid demo thumbnail: '+name);
    thumbnails[name]='data:image/jpeg;base64,'+bytes.toString('base64');
  }
  await writeFile(join(source,'demo-thumbnails.mjs'),'// Generated by scripts/generate-demo-thumbnails.mjs from the original official JPEGs.\nexport const DEMO_THUMBNAILS=Object.freeze('+JSON.stringify(thumbnails)+');\n');
}
if(process.argv[1]&&import.meta.url===pathToFileURL(resolve(process.argv[1])).href)await generateDemoThumbnails();
